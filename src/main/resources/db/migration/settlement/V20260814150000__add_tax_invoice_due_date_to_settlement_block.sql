-- 무엇: settlement_block 에 세금계산서 기한(tax_invoice_due_date) 컬럼을 추가한다.
-- 왜:   정산 회차마다 "언제까지 세금계산서를 받아야 하는지"를 사용자가 직접 입력해야 한다는 요구가
--       들어왔다(2026-08-14). 기존 planned_date 는 입출금 기한이라 세금계산서 기한과 의미가 다르다 —
--       세금계산서 매칭 추천의 일자 비교도 이 컬럼을 기준으로 바뀐다.
--
-- ⚠️ NULL 허용인 이유: 면세 거래처럼 세금계산서를 받지 않는 회차가 있어서 기한이 없는 게 정상이다
--    (사용자 확정). 기존 행도 값이 없으므로 NOT NULL 로 두면 마이그레이션 자체가 불가능하다.
--    기한이 NULL 인 블록은 세금계산서 매칭 추천에서 일자 기준만 탈락하고, 나머지 3기준
--    (금액·세액·상호명)으로는 그대로 후보에 오른다.
--
-- ⚠️ planned_date 는 이름을 바꾸지 않는다 — 프론트가 이미 plannedDate 필드를 쓰고 있어서 rename 하면
--    연동이 깨진다. "입출금 기한"이라는 명칭은 화면 라벨에서만 반영한다(2026-08-14 사용자 확정).

ALTER TABLE `settlement_block`
    ADD COLUMN `tax_invoice_due_date` DATE NULL COMMENT '세금계산서 기한 (없으면 NULL — 면세 등 세금계산서를 받지 않는 회차)'
        AFTER `planned_date`;
